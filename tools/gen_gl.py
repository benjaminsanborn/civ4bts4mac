"""Generate OpenGL pass-through shims (runtime/gl_gen.c) from the macOS SDK headers.

Each guest GL call reads its arguments from the guest stack (i386 cdecl:
float = 1 slot, double = 2 slots), translates guest pointers, and calls the
host function. Functions needing real logic are hand-written in gl_special.c
and listed in SPECIAL.

  python3 tools/gen_gl.py NAMES_FILE > runtime/gl_gen.c
"""
import os
import re
import subprocess
import sys

# Implemented by hand in runtime/gl_special.c.
SPECIAL = {
    "glBindBufferARB", "glMapBufferARB", "glUnmapBufferARB", "glFlushMappedBufferRangeAPPLE", "glGetString",
    "glShaderSourceARB", "glVertexPointer", "glNormalPointer", "glColorPointer", "glTexCoordPointer",
    "glSecondaryColorPointer", "glVertexAttribPointerARB", "glDrawRangeElements", "gluCheckExtension",
    "glBindFramebufferEXT", "glDrawBuffer", "glReadBuffer", "glViewport", "glScissor", "glGetIntegerv",
    "glGetFloatv", "glWindowPos2i", "glCopyPixels", "glReadPixels", "glCopyTexSubImage2D", "glCopyTexImage2D",
    "glTexImage2D", "glTexSubImage2D", "glDeleteTextures",  # gl_text.c
}

INT_TYPES = {"GLenum", "GLboolean", "GLbitfield", "GLbyte", "GLshort", "GLint", "GLsizei", "GLubyte", "GLushort",
             "GLuint", "GLsizeiptr", "GLintptr", "GLsizeiptrARB", "GLintptrARB", "GLcharARB", "GLchar", "int"}
FLOAT_TYPES = {"GLfloat", "GLclampf"}
DOUBLE_TYPES = {"GLdouble", "GLclampd"}


def sdk_headers():
    sdk = subprocess.check_output(["xcrun", "--show-sdk-path"], text=True).strip()
    d = os.path.join(sdk, "System/Library/Frameworks/OpenGL.framework/Headers")
    return [os.path.join(d, h) for h in ("gl.h", "glext.h")]


def parse_prototypes():
    protos = {}
    rx = re.compile(r"extern\s+([\w\s\*]+?)\s*\b(gl\w+)\s*\(([^)]*)\)")
    for h in sdk_headers():
        text = open(h).read()
        for ret, name, args in rx.findall(text):
            protos.setdefault(name, (" ".join(ret.split()), args.strip()))
    return protos


def split_arg(a):
    a = " ".join(a.replace("const", "").split())
    m = re.match(r"(.*?)(\w+)$", a)
    typ = m.group(1).strip() if m else a
    if not typ:  # unnamed parameter
        typ = a
    return typ.replace(" *", "*").replace("* ", "*")


def gen(name, ret, args):
    params = [] if args in ("", "void") else [split_arg(a) for a in args.split(",")]
    slot = 0
    exprs = []
    for t in params:
        if "*" in t:
            exprs.append(f"PTR(ARG({slot}))")
            slot += 1
        elif t in DOUBLE_TYPES:
            exprs.append(f"ARGF64({slot})")
            slot += 2
        elif t in FLOAT_TYPES:
            exprs.append(f"ARGF32({slot})")
            slot += 1
        elif t == "GLhandleARB":
            exprs.append(f"(GLhandleARB)(uintptr_t)ARG({slot})")
            slot += 1
        elif t in INT_TYPES:
            exprs.append(f"({t})ARG({slot})")
            slot += 1
        else:
            raise SystemExit(f"{name}: unknown parameter type {t!r}")
    call = f"{name}({', '.join(exprs)})"
    ret = ret.replace("const ", "").strip()
    if ret == "void":
        body = f"{call};"
    elif ret == "GLhandleARB":
        body = f"RET((uint32_t)(uintptr_t){call});"
    elif ret in INT_TYPES:
        body = f"RET({call});"
    else:
        raise SystemExit(f"{name}: unknown return type {ret!r}")
    return f"SHIM(_{name}) {{ {body} }}"


def main():
    names = open(sys.argv[1]).read().split()
    protos = parse_prototypes()
    out = ["/* Generated by tools/gen_gl.py from the SDK OpenGL headers. Do not edit. */",
           "#define GL_SILENCE_DEPRECATION 1", "#include <OpenGL/gl.h>", "#include <OpenGL/glext.h>",
           '#include "shim.h"', ""]
    entries = []
    for n in names:
        if n in SPECIAL:
            continue
        if n not in protos:
            raise SystemExit(f"no prototype for {n}")
        ret, args = protos[n]
        out.append(gen(n, ret, args))
        entries.append(f"SHIM_ENTRY(_{n})")
    out.append("")
    out.append("const ShimDef shims_gl_gen[] = {")
    for i in range(0, len(entries), 4):
        out.append("    " + ", ".join(entries[i:i + 4]) + ",")
    out.append("    {0, 0},")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
